// Post-build step: Cloudflare's static-asset layer ignores HTTP Range
// requests (200 + whole file, no Content-Range/Accept-Ranges), which makes
// browsers treat our audio as non-seekable — every seek snaps back to 0:00.
// vite.config.ts routes /audio/* to the Worker first (run_worker_first);
// this script turns the Worker entry into a thin wrapper that serves proper
// 206 Partial Content responses for /audio/* and delegates everything else
// to the untouched nitro entry.
//
// Steps: rename nitro's index.mjs -> worker-core.mjs, write the wrapper as
// index.mjs (wrangler.json keeps main: "index.mjs"), and verify the routing
// config actually shipped. Idempotent: re-running without a rebuild is a
// no-op (wrapper marker detected).
import {
  readFileSync,
  writeFileSync,
  existsSync,
  unlinkSync,
  renameSync,
} from "node:fs";
import { join } from "node:path";

const serverDir = join(process.cwd(), ".output", "server");
const entryPath = join(serverDir, "index.mjs");
const corePath = join(serverDir, "worker-core.mjs");
const wranglerPath = join(serverDir, "wrangler.json");
const MARKER = "/* prc-dor audio range wrapper */";

const entry = readFileSync(entryPath, "utf8");
if (entry.startsWith(MARKER)) {
  if (!existsSync(corePath)) {
    throw new Error(
      "postbuild-audio-ranges: wrapper present but worker-core.mjs is missing",
    );
  }
  console.log("[postbuild-audio-ranges] already post-processed, skipping");
  process.exit(0);
}

const wrangler = JSON.parse(readFileSync(wranglerPath, "utf8"));
const runFirst = wrangler.assets?.run_worker_first;
if (!Array.isArray(runFirst) || !runFirst.includes("/audio/*")) {
  throw new Error(
    'postbuild-audio-ranges: wrangler.json assets.run_worker_first must include "/audio/*" (check vite.config.ts nitro cloudflare.wrangler config)',
  );
}
if (wrangler.main !== "index.mjs") {
  throw new Error(
    `postbuild-audio-ranges: unexpected wrangler.json main "${wrangler.main}"`,
  );
}

// A stale core from a previous build must not survive: vite rewrites
// index.mjs fresh each build, so whatever sits in worker-core.mjs now is old.
if (existsSync(corePath)) unlinkSync(corePath);
renameSync(entryPath, corePath);

const wrapper = `${MARKER}
// Generated by scripts/postbuild-audio-ranges.mjs — do not edit.
import worker from "./worker-core.mjs";

const AUDIO_PREFIX = "/audio/";

// Single RFC 9110 byte-range form only ("bytes=a-b", "bytes=a-", "bytes=-n");
// anything else (multi-range, malformed) falls back to a full 200 response.
function parseByteRange(header, size) {
  const match = /^\\s*bytes=(\\d*)-(\\d*)\\s*$/.exec(header);
  if (!match || (match[1] === "" && match[2] === "")) return { unsupported: true };
  let start;
  let end;
  if (match[1] === "") {
    const suffix = Number(match[2]);
    if (suffix === 0) return { unsatisfiable: true };
    start = Math.max(0, size - suffix);
    end = size - 1;
  } else {
    start = Number(match[1]);
    end = match[2] === "" ? size - 1 : Number(match[2]);
    if (match[2] !== "" && end < start) return { unsatisfiable: true };
    if (end > size - 1) end = size - 1;
    if (start > size - 1) return { unsatisfiable: true };
  }
  if (start > end) return { unsatisfiable: true };
  return { start, end };
}

async function serveAudioWithRanges(request, env) {
  if (request.method !== "GET" && request.method !== "HEAD") {
    return env.ASSETS.fetch(request);
  }

  // Fresh GET — never forward the client's Range/If-* headers: the assets
  // binding ignores ranges anyway, and conditional headers could return a
  // body-less 304 we would be unable to slice.
  const url = new URL(request.url);
  const asset = await env.ASSETS.fetch(new Request(url));
  if (!asset.ok) return asset;

  const body = await asset.arrayBuffer();
  const size = body.byteLength;
  const headers = new Headers(asset.headers);
  headers.set("accept-ranges", "bytes");

  const full = () => {
    headers.set("content-length", String(size));
    headers.delete("content-range");
    return new Response(request.method === "HEAD" ? null : body, { status: 200, headers });
  };

  const range = request.headers.get("range");
  if (!range) return full();

  // If-Range only honours the range when the validator still matches.
  const ifRange = request.headers.get("if-range");
  if (ifRange && ifRange !== (asset.headers.get("etag") ?? "")) return full();

  const parsed = parseByteRange(range, size);
  if (!parsed || parsed.unsupported) return full();
  if (parsed.unsatisfiable) {
    headers.set("content-range", \`bytes */\${size}\`);
    headers.set("content-length", "0");
    return new Response(null, { status: 416, headers });
  }

  const { start, end } = parsed;
  const slice = body.slice(start, end + 1);
  headers.set("content-range", \`bytes \${start}-\${end}/\${size}\`);
  headers.set("content-length", String(end - start + 1));
  return new Response(request.method === "HEAD" ? null : slice, { status: 206, headers });
}

export default {
  ...worker,
  async fetch(request, env, ctx) {
    if (env.ASSETS && new URL(request.url).pathname.startsWith(AUDIO_PREFIX)) {
      try {
        return await serveAudioWithRanges(request, env);
      } catch (error) {
        console.error("audio range handler failed, falling through:", error);
      }
    }
    return worker.fetch(request, env, ctx);
  },
};
`;

writeFileSync(entryPath, wrapper, "utf8");
console.log(
  "[postbuild-audio-ranges] wrote range-serving Worker wrapper (index.mjs -> worker-core.mjs)",
);
