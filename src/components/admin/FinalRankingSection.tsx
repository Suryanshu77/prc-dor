// Admin > Final Ranking Control.
//
// The calculated ranking (aggregate points from valid ballots) and the final
// published order are two separate things: this panel only ever writes the
// latter, through admin_save_final_ranking / admin_reset_final_ranking, which
// store rows in public.final_rankings. Vote records, ballot rankings and point
// totals are never touched — the public results page keeps showing the real
// aggregate points next to the manually approved positions.
//
// Publication reuses the existing voting_periods.results_visible /
// results_published flags, so there is no second, competing visibility system.
//
// Row types are declared locally because the generated Database types are
// regenerated by the Lovable/Supabase workflow after the migration lands.
import { useEffect, useMemo, useState } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import {
  DndContext,
  closestCenter,
  PointerSensor,
  TouchSensor,
  KeyboardSensor,
  useSensor,
  useSensors,
  type DragEndEvent,
} from "@dnd-kit/core";
import {
  SortableContext,
  arrayMove,
  useSortable,
  verticalListSortingStrategy,
} from "@dnd-kit/sortable";
import { CSS } from "@dnd-kit/utilities";
import { supabase } from "@/integrations/supabase/client";
import { Button } from "@/components/ui/button";
import { Label } from "@/components/ui/label";
import { Switch } from "@/components/ui/switch";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from "@/components/ui/alert-dialog";
import { PlayerAvatar } from "@/components/PlayerAvatar";
import { toast } from "sonner";
import {
  ArrowDown,
  ArrowUp,
  Crown,
  GripVertical,
  Lock,
  RotateCcw,
  Save,
  Send,
  Trophy,
  Undo2,
} from "lucide-react";

type RankingRow = {
  player_id: string;
  full_name: string | null;
  nickname: string | null;
  player_position: string | null;
  jersey_number: number | null;
  profile_image: string | null;
  total_points: number;
  first_place_votes: number;
  total_rankings: number;
  calculated_rank: number;
  calculated_row: number;
  final_position: number | null;
  approved_at: string | null;
};

type FinalRankingRow = {
  id: string;
  voting_period_id: string;
  player_id: string;
  final_position: number;
  calculated_position: number | null;
  approved_by: string | null;
  approved_at: string;
};

export default function FinalRankingSection() {
  const qc = useQueryClient();

  const periodsQ = useQuery({
    queryKey: ["periods"],
    queryFn: async () => {
      const { data } = await supabase
        .from("voting_periods")
        .select("*")
        .order("year", { ascending: false });
      return data ?? [];
    },
  });
  const periods = useMemo(() => periodsQ.data ?? [], [periodsQ.data]);
  const [periodId, setPeriodId] = useState<string | undefined>(undefined);
  useEffect(() => {
    if (
      periods.length &&
      (!periodId || !periods.some((p) => p.id === periodId))
    ) {
      setPeriodId(periods[0].id);
    }
  }, [periods, periodId]);
  const period = periods.find((p) => p.id === periodId);

  const previewQ = useQuery({
    queryKey: ["final-ranking-preview", periodId],
    enabled: !!periodId,
    queryFn: async () => {
      const { data, error } = await supabase.rpc("admin_get_ranking_preview", {
        _period_id: periodId!,
      });
      if (error) {
        console.error("[ranking] failed to load the ranking preview", error);
        toast.error("Couldn't load the ranking for this edition.", {
          id: "final-ranking-preview",
        });
      }
      return (data ?? []) as RankingRow[];
    },
  });

  const savedQ = useQuery({
    queryKey: ["final-rankings", periodId],
    enabled: !!periodId,
    queryFn: async () => {
      const { data, error } = await supabase
        .from("final_rankings")
        .select(
          "id, voting_period_id, player_id, final_position, calculated_position, approved_by, approved_at",
        )
        .eq("voting_period_id", periodId!)
        .order("final_position", { ascending: true });
      if (error) {
        console.error("[ranking] failed to load the saved ranking", error);
        return [] as FinalRankingRow[];
      }
      return (data ?? []) as FinalRankingRow[];
    },
  });

  const players = useMemo(() => previewQ.data ?? [], [previewQ.data]);
  const saved = useMemo(() => savedQ.data ?? [], [savedQ.data]);
  const byId = useMemo(
    () => new Map(players.map((p) => [p.player_id, p])),
    [players],
  );

  const [order, setOrder] = useState<string[]>([]);
  const [baseOrder, setBaseOrder] = useState<string[]>([]);

  // Seed the editor from the saved order when one exists, otherwise from the
  // calculated ranking. Both are the same player set, so the editor can never
  // invent or drop a player.
  useEffect(() => {
    if (!players.length) {
      setOrder([]);
      setBaseOrder([]);
      return;
    }
    const savedIds = [...saved]
      .sort((a, b) => a.final_position - b.final_position)
      .map((r) => r.player_id);
    const complete =
      savedIds.length === players.length &&
      savedIds.every((id) => byId.has(id));
    const next = complete ? savedIds : players.map((p) => p.player_id);
    setOrder(next);
    setBaseOrder(next);
  }, [players, saved, byId]);

  const dirty = order.join(",") !== baseOrder.join(",");
  const manuallyAdjusted = saved.length > 0;
  const sensors = useSensors(
    useSensor(PointerSensor),
    useSensor(TouchSensor),
    useSensor(KeyboardSensor),
  );

  const [confirmSave, setConfirmSave] = useState(false);
  const [confirmReset, setConfirmReset] = useState(false);
  const [confirmPublish, setConfirmPublish] = useState(false);
  const [busy, setBusy] = useState(false);

  // Players sharing a calculated rank (same points and same first-place votes)
  // are flagged so the admin knows the calculated order was arbitrary there.
  const tiedRanks = useMemo(() => {
    const counts = new Map<number, number>();
    for (const p of players)
      counts.set(p.calculated_rank, (counts.get(p.calculated_rank) ?? 0) + 1);
    return new Set(
      [...counts.entries()].filter(([, n]) => n > 1).map(([rank]) => rank),
    );
  }, [players]);

  function move(playerId: string, delta: number) {
    setOrder((prev) => {
      const from = prev.indexOf(playerId);
      const to = from + delta;
      if (from < 0 || to < 0 || to >= prev.length) return prev;
      return arrayMove(prev, from, to);
    });
  }

  function onDragEnd(e: DragEndEvent) {
    const { active, over } = e;
    if (!over || active.id === over.id) return;
    setOrder((prev) => {
      const from = prev.indexOf(String(active.id));
      const to = prev.indexOf(String(over.id));
      if (from < 0 || to < 0) return prev;
      return arrayMove(prev, from, to);
    });
  }

  async function save() {
    if (!periodId) return;
    setBusy(true);
    const { data, error } = await supabase.rpc("admin_save_final_ranking", {
      _period_id: periodId,
      _player_ids: order,
    });
    setBusy(false);
    setConfirmSave(false);
    if (error) {
      console.error("[ranking] save failed", error);
      toast.error(error.message || "Couldn't save the final ranking.");
      return;
    }
    toast.success(`Final ranking saved (${data} positions approved).`);
    qc.invalidateQueries({ queryKey: ["final-rankings"] });
    qc.invalidateQueries({ queryKey: ["final-ranking-preview"] });
    qc.invalidateQueries({ queryKey: ["leaderboard"] });
    qc.invalidateQueries({ queryKey: ["admin-audit-log"] });
    qc.invalidateQueries({ queryKey: ["player-period-rank"] });
  }

  async function reset() {
    if (!periodId) return;
    setBusy(true);
    const { data, error } = await supabase.rpc("admin_reset_final_ranking", {
      _period_id: periodId,
    });
    setBusy(false);
    setConfirmReset(false);
    if (error) {
      console.error("[ranking] reset failed", error);
      toast.error(error.message || "Couldn't reset the final ranking.");
      return;
    }
    toast.success(
      data > 0
        ? "Manual order removed — the calculated ranking is back in force."
        : "No manual order was stored for this edition.",
    );
    qc.invalidateQueries({ queryKey: ["final-rankings"] });
    qc.invalidateQueries({ queryKey: ["final-ranking-preview"] });
    qc.invalidateQueries({ queryKey: ["leaderboard"] });
    qc.invalidateQueries({ queryKey: ["admin-audit-log"] });
    qc.invalidateQueries({ queryKey: ["player-period-rank"] });
  }

  async function publish() {
    if (!periodId) return;
    setBusy(true);
    const { error } = await supabase
      .from("voting_periods")
      .update({ results_visible: true, results_published: true })
      .eq("id", periodId);
    setBusy(false);
    setConfirmPublish(false);
    if (error) {
      console.error("[ranking] publish failed", error);
      toast.error(error.message || "Couldn't publish the results.");
      return;
    }
    toast.success("Results published — the final order is now public.");
    qc.invalidateQueries({ queryKey: ["periods"] });
    qc.invalidateQueries({ queryKey: ["leaderboard"] });
    qc.invalidateQueries({ queryKey: ["results-visible"] });
    qc.invalidateQueries({ queryKey: ["years"] });
  }

  return (
    <section className="glass-strong rounded-2xl p-6">
      <div className="mb-1 flex items-center justify-between gap-4">
        <div className="flex items-center gap-2">
          <Trophy className="h-5 w-5 text-gold" />
          <h2 className="font-display text-2xl">Final Ranking Control</h2>
        </div>
        {manuallyAdjusted && (
          <span className="rounded-full border border-gold/40 bg-secondary/40 px-3 py-1 text-xs text-gold">
            Manually adjusted
          </span>
        )}
      </div>
      <p className="mb-5 max-w-2xl text-sm text-muted-foreground">
        Rearrange the calculated ranking into the order you want to publish.
        Saving only stores the order — every player's point total, every ballot
        and every vote record stays exactly as voted. Reset returns the edition
        to the points-based order.
      </p>

      <div className="mb-4 flex flex-wrap items-end gap-3">
        <div className="w-56">
          <Label>Edition</Label>
          <Select value={periodId} onValueChange={setPeriodId}>
            <SelectTrigger>
              <SelectValue placeholder="Select an edition" />
            </SelectTrigger>
            <SelectContent>
              {periods.map((p) => (
                <SelectItem key={p.id} value={p.id}>
                  {p.title}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>

        {period && (
          <div className="flex items-center gap-4 text-sm">
            <span className="flex items-center gap-2">
              Live results
              <Switch
                checked={period.results_visible ?? false}
                onCheckedChange={async (visible) => {
                  await supabase
                    .from("voting_periods")
                    .update({ results_visible: visible })
                    .eq("id", period.id);
                  qc.invalidateQueries({ queryKey: ["periods"] });
                  qc.invalidateQueries({ queryKey: ["leaderboard"] });
                  qc.invalidateQueries({ queryKey: ["results-visible"] });
                }}
              />
            </span>
            <span
              className={`flex items-center gap-1 text-xs ${period.is_active ? "text-green-400" : "text-red-400"}`}
            >
              <span
                className={`h-1.5 w-1.5 rounded-full ${period.is_active ? "bg-green-400" : "bg-red-400"}`}
              />
              {period.is_active ? "VOTING OPEN" : "VOTING CLOSED"}
            </span>
            <span
              className={`flex items-center gap-1 text-xs ${period.results_published ? "text-green-400" : "text-muted-foreground"}`}
            >
              <span
                className={`h-1.5 w-1.5 rounded-full ${period.results_published ? "bg-green-400" : "bg-muted-foreground"}`}
              />
              {period.results_published ? "PUBLISHED" : "NOT ANNOUNCED"}
            </span>
          </div>
        )}

        <div className="ml-auto flex flex-wrap items-center gap-2">
          <Button
            size="sm"
            variant="outline"
            onClick={() => setOrder(baseOrder)}
            disabled={!dirty}
          >
            <Undo2 className="mr-1 h-4 w-4" /> Undo changes
          </Button>
          <Button
            size="sm"
            variant="outline"
            onClick={() => setConfirmReset(true)}
            disabled={busy || !manuallyAdjusted}
          >
            <RotateCcw className="mr-1 h-4 w-4" /> Reset to calculated
          </Button>
          <Button
            size="sm"
            variant="outline"
            onClick={() => setConfirmSave(true)}
            disabled={busy || !dirty || players.length === 0}
          >
            <Save className="mr-1 h-4 w-4" /> Save final ranking
          </Button>
          <Button
            size="sm"
            onClick={() => setConfirmPublish(true)}
            disabled={busy || !periodId}
            className="bg-gold-gradient text-background hover:opacity-90"
          >
            <Send className="mr-1 h-4 w-4" /> Publish results
          </Button>
        </div>
      </div>

      {period?.is_active && (
        <div className="mb-4 rounded-lg border border-gold/30 bg-secondary/30 px-3 py-2 text-sm text-gold">
          Voting is still open for this edition. Close it before publishing so
          the ranking you approve is final.
        </div>
      )}

      {previewQ.isLoading ? (
        <div className="rounded-xl border border-dashed border-border p-8 text-center text-sm text-muted-foreground">
          Loading the ranking…
        </div>
      ) : players.length === 0 ? (
        <div className="rounded-xl border border-dashed border-border p-8 text-center text-sm text-muted-foreground">
          No player has scored a point in this edition yet.
        </div>
      ) : (
        <>
          <DndContext
            sensors={sensors}
            collisionDetection={closestCenter}
            onDragEnd={onDragEnd}
          >
            <SortableContext
              items={order}
              strategy={verticalListSortingStrategy}
            >
              <ol className="space-y-2">
                {order.map((playerId, index) => (
                  <SortableRankingRow
                    key={playerId}
                    player={byId.get(playerId)}
                    index={index}
                    calculatedRow={byId.get(playerId)?.calculated_row ?? 0}
                    tied={tiedRanks.has(
                      byId.get(playerId)?.calculated_rank ?? 0,
                    )}
                    onMove={(delta) => move(playerId, delta)}
                    canUp={index > 0}
                    canDown={index < order.length - 1}
                  />
                ))}
              </ol>
            </SortableContext>
          </DndContext>

          <div className="mt-4 flex flex-wrap items-center justify-between gap-2 text-xs text-muted-foreground">
            <span>
              Drag the handle, or use the ▲ / ▼ buttons, to change the final
              position. Points are display-only and never change.
            </span>
            {dirty && <span className="text-gold">Unsaved changes</span>}
          </div>
        </>
      )}

      {/* Save */}
      <AlertDialog open={confirmSave} onOpenChange={setConfirmSave}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Save this final ranking?</AlertDialogTitle>
            <AlertDialogDescription>
              The order below becomes the published order for{" "}
              <span className="font-semibold text-foreground">
                {period?.title}
              </span>
              . Point totals and all vote records stay unchanged. You can still
              rearrange or reset it until the results are published.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel disabled={busy}>Cancel</AlertDialogCancel>
            <AlertDialogAction
              disabled={busy}
              onClick={(e) => {
                e.preventDefault();
                save();
              }}
            >
              {busy ? "Saving…" : "Save final ranking"}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>

      {/* Reset */}
      <AlertDialog open={confirmReset} onOpenChange={setConfirmReset}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>
              Reset to the calculated ranking?
            </AlertDialogTitle>
            <AlertDialogDescription>
              The manually approved order is deleted and results fall back to
              the points-based ranking. No ballot or point total is affected.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel disabled={busy}>Cancel</AlertDialogCancel>
            <AlertDialogAction
              disabled={busy}
              onClick={(e) => {
                e.preventDefault();
                reset();
              }}
            >
              {busy ? "Resetting…" : "Reset ranking"}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>

      {/* Publish */}
      <AlertDialog open={confirmPublish} onOpenChange={setConfirmPublish}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Publish the results?</AlertDialogTitle>
            <AlertDialogDescription>
              This makes the {period?.year} results — including{" "}
              {manuallyAdjusted
                ? "your manually approved order"
                : "the calculated order"}{" "}
              — visible to every signed-in user, and marks the edition as
              announced. Players will still see the real aggregate points next
              to each position.
              {dirty && (
                <span className="mt-2 block text-destructive">
                  You have unsaved rearrangements: save them first if they
                  should be the ones published.
                </span>
              )}
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel disabled={busy}>Cancel</AlertDialogCancel>
            <AlertDialogAction
              disabled={busy}
              onClick={(e) => {
                e.preventDefault();
                publish();
              }}
            >
              {busy ? "Publishing…" : "Publish results"}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </section>
  );
}

function SortableRankingRow({
  player,
  index,
  calculatedRow,
  tied,
  onMove,
  canUp,
  canDown,
}: {
  player: RankingRow | undefined;
  index: number;
  calculatedRow: number;
  tied: boolean;
  onMove: (delta: number) => void;
  canUp: boolean;
  canDown: boolean;
}) {
  const {
    attributes,
    listeners,
    setNodeRef,
    transform,
    transition,
    isDragging,
  } = useSortable({ id: player?.player_id ?? `empty-${index}` });
  const style = {
    transform: CSS.Transform.toString(transform),
    transition,
    opacity: isDragging ? 0.6 : 1,
  };

  if (!player) return null;
  const delta = calculatedRow - (index + 1);

  return (
    <li
      ref={setNodeRef}
      style={style}
      className="flex items-center gap-3 rounded-xl border border-[var(--gold)]/25 bg-secondary/30 p-3"
    >
      <button
        {...attributes}
        {...listeners}
        className="cursor-grab touch-none text-muted-foreground"
        aria-label={`Reorder ${player.full_name ?? "player"}`}
      >
        <GripVertical className="h-5 w-5" />
      </button>

      <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-gold-gradient font-display text-sm text-background">
        {index + 1}
      </div>

      <PlayerAvatar
        path={player.profile_image}
        name={player.full_name ?? ""}
        className="h-10 w-10"
      />

      <div className="min-w-0 flex-1">
        <div className="flex flex-wrap items-center gap-2">
          <span className="truncate text-sm font-medium">
            {player.full_name}
          </span>
          {tied && (
            <span className="rounded-full border border-border px-1.5 py-0.5 text-[10px] uppercase tracking-wider text-muted-foreground">
              calculated tie
            </span>
          )}
        </div>
        <div className="text-xs text-muted-foreground">
          Calculated #{calculatedRow}
          {tied ? ` (rank ${player.calculated_rank})` : ""}
          {delta > 0 && (
            <span className="ml-2 text-gold">
              <Crown className="mr-1 inline h-3 w-3" />
              moved up {delta}
            </span>
          )}
          {delta < 0 && (
            <span className="ml-2 text-muted-foreground">
              moved down {-delta}
            </span>
          )}
        </div>
      </div>

      <div className="text-right">
        <div className="font-display text-base text-gold-gradient">
          {player.total_points}
        </div>
        <div className="text-[10px] uppercase tracking-widest text-muted-foreground">
          points
        </div>
      </div>

      <div className="flex flex-col gap-1">
        <button
          onClick={() => onMove(-1)}
          disabled={!canUp}
          aria-label={`Move ${player.full_name ?? "player"} up`}
          className="rounded-md border border-border p-1 text-muted-foreground transition hover:text-gold disabled:opacity-30"
        >
          <ArrowUp className="h-3.5 w-3.5" />
        </button>
        <button
          onClick={() => onMove(1)}
          disabled={!canDown}
          aria-label={`Move ${player.full_name ?? "player"} down`}
          className="rounded-md border border-border p-1 text-muted-foreground transition hover:text-gold disabled:opacity-30"
        >
          <ArrowDown className="h-3.5 w-3.5" />
        </button>
      </div>

      {!player.final_position && (
        <Lock className="h-3.5 w-3.5 text-muted-foreground/40" />
      )}
    </li>
  );
}
